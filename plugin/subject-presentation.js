const clean = (value, min, max) => {
  if (typeof value !== 'string') return null;
  const text = value.trim();
  return text.length >= min && text.length <= max && /\p{Script=Han}/u.test(text) && !/[<>\r\n\p{Cc}]|https?:\/\//iu.test(text) ? text : null;
};

